package openapi

import (
	"context"

	"github.com/antihax/optional"

	openapi "github.com/storageos/go-api/autogenerated"
	apiclient "github.com/storageos/kubectl-storageos/api_client"
	"github.com/storageos/kubectl-storageos/model"
)

// GetCluster requests the cluster configuration from the StorageOS API,
// translating it into a *model.Cluster.
func (o *OpenAPI) GetCluster(ctx context.Context) (*model.Cluster, error) {
	o.mu.RLock()
	defer o.mu.RUnlock()

	model, resp, err := o.client.DefaultApi.GetCluster(ctx)
	if err != nil {
		return nil, mapOpenAPIError(err, resp)
	}

	return DecodeCluster(model)
}

// UpdateCluster attempts to perform an update of the cluster configuration
// through the StorageOS API using resource as the update value.
func (o *OpenAPI) UpdateCluster(ctx context.Context, resource *model.Cluster, params *apiclient.UpdateClusterRequestParams) (*model.Cluster, error) {
	o.mu.RLock()
	defer o.mu.RUnlock()

	level, err := EncodeLogLevel(resource.LogLevel)
	if err != nil {
		return nil, err
	}

	format, err := EncodeLogFormat(resource.LogFormat)
	if err != nil {
		return nil, err
	}

	updateData := openapi.UpdateClusterData{
		DisableTelemetry:      resource.DisableTelemetry,
		DisableCrashReporting: resource.DisableCrashReporting,
		DisableVersionCheck:   resource.DisableVersionCheck,
		LogLevel:              level,
		LogFormat:             format,
	}

	opts := &openapi.UpdateClusterOpts{
		IgnoreVersion: optional.NewBool(true),
	}

	// check optional params
	if params != nil && params.CASVersion != "" {
		updateData.Version = params.CASVersion
		opts.IgnoreVersion = optional.NewBool(false)
	}

	model, resp, err := o.client.DefaultApi.UpdateCluster(ctx, updateData, opts)
	if err != nil {
		return nil, mapOpenAPIError(err, resp)
	}

	return DecodeCluster(model)
}
