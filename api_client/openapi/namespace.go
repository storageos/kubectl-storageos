package openapi

import (
	"context"

	"github.com/antihax/optional"

	openapi "github.com/storageos/go-api/autogenerated"
	apiclient "github.com/storageos/kubectl-storageos/api_client"
	"github.com/storageos/kubectl-storageos/model"
)

// GetNamespace requests the namespace with uid from the StorageOS API,
// translating it into a *model.Namespace.
func (o *OpenAPI) GetNamespace(ctx context.Context, uid string) (*model.Namespace, error) {
	o.mu.RLock()
	defer o.mu.RUnlock()

	model, resp, err := o.client.DefaultApi.GetNamespace(ctx, uid)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		case notFoundError:
			return nil, apiclient.NewNamespaceNotFoundError(uid)
		default:
			return nil, v
		}
	}

	return DecodeNamespace(model)
}

// ListNamespaces requests a list of all namespaces from the StorageOS API,
// translating each one to a *model.Namespace.
func (o *OpenAPI) ListNamespaces(ctx context.Context) ([]*model.Namespace, error) {
	o.mu.RLock()
	defer o.mu.RUnlock()

	models, resp, err := o.client.DefaultApi.ListNamespaces(ctx)
	if err != nil {
		return nil, mapOpenAPIError(err, resp)
	}

	namespaces := make([]*model.Namespace, len(models))
	for i, m := range models {
		ns, err := DecodeNamespace(m)
		if err != nil {
			return nil, err
		}

		namespaces[i] = ns
	}

	return namespaces, nil
}

// CreateNamespace requests the creation of a new namespace through the
// StorageOS API using the provided parameters.
func (o *OpenAPI) CreateNamespace(ctx context.Context, name string, labels map[string]string) (*model.Namespace, error) {
	createData := openapi.CreateNamespaceData{
		Name:   name,
		Labels: labels,
	}

	model, resp, err := o.client.DefaultApi.CreateNamespace(ctx, createData)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		case badRequestError:
			return nil, apiclient.NewInvalidNamespaceCreationError(v.msg)
		case conflictError:
			return nil, apiclient.NewNamespaceExistsError(name)
		default:
			return nil, v
		}
	}

	return DecodeNamespace(model)
}

// DeleteNamespace makes a delete request for a namespace given its ID.
//
// The behaviour of the operation is dictated by params:
//
//	Version constraints:
//	- If params is nil or params.CASVersion is empty then the delete request is
//	unconditional
//	- If params.CASVersion is set, the request is conditional upon it matching
//	the volume entity's version as seen by the server.
func (o *OpenAPI) DeleteNamespace(ctx context.Context, uid string, params *apiclient.DeleteNamespaceRequestParams) error {
	o.mu.RLock()
	defer o.mu.RUnlock()

	var casVersion string
	var ignoreVersion optional.Bool = optional.NewBool(true)

	if params != nil {
		if params.CASVersion != "" {
			ignoreVersion = optional.NewBool(false)
			casVersion = params.CASVersion
		}
	}

	resp, err := o.client.DefaultApi.DeleteNamespace(
		ctx,
		uid,
		casVersion,
		&openapi.DeleteNamespaceOpts{
			IgnoreVersion: ignoreVersion,
		},
	)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		case notFoundError:
			return apiclient.NewNamespaceNotFoundError(uid)
		default:
			return v
		}
	}

	return nil
}
