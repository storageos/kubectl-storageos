package openapi

import (
	"context"

	"github.com/antihax/optional"

	openapi "github.com/storageos/go-api/autogenerated"
	"github.com/storageos/kubectl-storageos/model"
)

// UpdateLicenceRequestParams contains optional request parameters for a update
// licence operation.
type UpdateLicenceRequestParams struct {
	CASVersion string
}

func (o *OpenAPI) GetLicence(ctx context.Context) (*model.License, error) {
	o.mu.RLock()
	defer o.mu.RUnlock()

	model, resp, err := o.client.DefaultApi.GetLicence(ctx)
	if err != nil {
		return nil, mapOpenAPIError(err, resp)
	}

	return DecodeLicence(model)
}

// UpdateLicence sends a new version of the licence to apply to the current
// cluster. It returns the new licence resource if correctly applied.
func (o *OpenAPI) UpdateLicence(ctx context.Context, licence []byte, params *UpdateLicenceRequestParams) (*model.License, error) {
	o.mu.RLock()
	defer o.mu.RUnlock()

	// default
	req := openapi.UpdateLicence{
		Key: string(licence),
	}
	opts := &openapi.UpdateLicenceOpts{
		IgnoreVersion: optional.NewBool(true),
	}

	// check optional params
	if params != nil && params.CASVersion != "" {
		req.Version = params.CASVersion
		opts.IgnoreVersion = optional.NewBool(false)
	}

	lic, resp, err := o.client.DefaultApi.UpdateLicence(ctx, req, opts)
	if err != nil {
		return nil, mapOpenAPIError(err, resp)
	}

	return DecodeLicence(lic)
}
