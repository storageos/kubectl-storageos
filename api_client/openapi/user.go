package openapi

import (
	"context"

	"github.com/antihax/optional"

	openapi "github.com/storageos/go-api/autogenerated"
	apiclient "github.com/storageos/kubectl-storageos/api_client"
	"github.com/storageos/kubectl-storageos/model"
)

func (o *OpenAPI) CreateUser(ctx context.Context, username, password string, withAdmin bool, groups ...string) (*model.User, error) {

	gs := make([]string, len(groups))
	copy(gs, groups)

	createData := openapi.CreateUserData{
		Username: username,
		Password: password,
		IsAdmin:  withAdmin,
		Groups:   &gs,
	}

	model, resp, err := o.client.DefaultApi.CreateUser(ctx, createData)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		case badRequestError:
			return nil, apiclient.NewInvalidUserCreationError(v.msg)
		case conflictError:
			return nil, apiclient.NewUserExistsError(username)
		default:
			return nil, v
		}
	}

	return DecodeUser(model)
}

func (o *OpenAPI) GetUser(ctx context.Context, uID string) (*model.User, error) {
	model, resp, err := o.client.DefaultApi.GetUser(ctx, uID)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		case notFoundError:
			return nil, apiclient.NewUserNotFoundError(v.msg, uID)
		default:
			return nil, v
		}
	}

	return DecodeUser(model)
}

func (o *OpenAPI) ListUsers(ctx context.Context) ([]*model.User, error) {
	list, resp, err := o.client.DefaultApi.ListUsers(ctx)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		default:
			return nil, v
		}
	}

	users := make([]*model.User, 0, len(list))

	for _, u := range list {
		u, err := DecodeUser(u)
		if err != nil {
			return nil, err
		}
		users = append(users, u)
	}

	return users, nil
}

// DeleteUser makes a delete request for a user given its ID.
//
// The behaviour of the operation is dictated by params:
//
//	Version constraints:
//	- If params is nil or params.CASVersion is empty then the delete request is
//	unconditional
//	- If params.CASVersion is set, the request is conditional upon it matching
//	the volume entity's version as seen by the server.
func (o *OpenAPI) DeleteUser(ctx context.Context, uid string, params *apiclient.DeleteUserRequestParams) error {
	o.mu.RLock()
	defer o.mu.RUnlock()

	var casVersion string
	var ignoreVersion optional.Bool = optional.NewBool(true)

	if params != nil {
		if params.CASVersion != "" {
			ignoreVersion = optional.NewBool(false)
			casVersion = params.CASVersion
		}
	}

	resp, err := o.client.DefaultApi.DeleteUser(
		ctx,
		uid,
		casVersion,
		&openapi.DeleteUserOpts{
			IgnoreVersion: ignoreVersion,
		},
	)
	if err != nil {
		switch v := mapOpenAPIError(err, resp).(type) {
		case notFoundError:
			return apiclient.NewUserNotFoundError(v.msg, uid)
		default:
			return v
		}
	}

	return nil
}
