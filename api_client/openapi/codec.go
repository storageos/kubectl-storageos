package openapi

import (
	"errors"

	openapi "github.com/storageos/go-api/autogenerated"
	apiclient "github.com/storageos/kubectl-storageos/api_client"
	"github.com/storageos/kubectl-storageos/model"
	"github.com/storageos/kubectl-storageos/pkg/health"
)

// codec provides functionality to encode/decode openapi models, translating
// them to/from internal types.

func DecodeCluster(cluster openapi.Cluster) (*model.Cluster, error) {
	return &model.Cluster{
		ID: cluster.Id,

		DisableTelemetry:      cluster.DisableTelemetry,
		DisableCrashReporting: cluster.DisableCrashReporting,
		DisableVersionCheck:   cluster.DisableVersionCheck,

		LogLevel:  model.LogLevelFromString(string(cluster.LogLevel)),
		LogFormat: model.LogFormatFromString(string(cluster.LogFormat)),

		CreatedAt: cluster.CreatedAt,
		UpdatedAt: cluster.UpdatedAt,
		Version:   cluster.Version,
	}, nil
}

func DecodeLicence(license openapi.Licence) (*model.License, error) {
	features := make([]string, 0)
	if license.Features != nil {
		features = append(features, *license.Features...)
	}

	return &model.License{
		ClusterID:            license.ClusterID,
		ExpiresAt:            license.ExpiresAt,
		ClusterCapacityBytes: license.ClusterCapacityBytes,
		UsedBytes:            license.UsedBytes,
		Kind:                 license.Kind,
		CustomerName:         license.CustomerName,
		Features:             features,
		Version:              license.Version,
	}, nil
}

func DecodeCapacityStats(stats openapi.CapacityStats) model.Stats {
	return model.Stats{
		Total: stats.Total,
		Free:  stats.Free,
	}
}

func DecodeNode(node openapi.Node) (*model.Node, error) {
	return &model.Node{
		ID:       string(node.Id),
		Name:     node.Name,
		Health:   health.NodeFromString(string(node.Health)),
		Capacity: DecodeCapacityStats(node.Capacity),

		Labels: node.Labels,

		IOAddr:         node.IoEndpoint,
		SupervisorAddr: node.SupervisorEndpoint,
		GossipAddr:     node.GossipEndpoint,
		ClusteringAddr: node.ClusteringEndpoint,

		Cordoned:   node.Cordoned,
		CordonedAt: node.CordonedAt,

		CreatedAt: node.CreatedAt,
		UpdatedAt: node.UpdatedAt,
		Version:   node.Version,
	}, nil
}

func DecodeVolume(vol openapi.Volume) (*model.Volume, error) {
	v := &model.Volume{
		ID:             string(vol.Id),
		Name:           vol.Name,
		Description:    vol.Description,
		SizeBytes:      vol.SizeBytes,
		AttachedOn:     string(vol.AttachedOn),
		AttachmentType: model.AttachTypeFromString(string(vol.AttachmentType)),
		Nfs:            DecodeNFSConfig(vol.Nfs),

		Namespace:      string(vol.NamespaceID),
		Labels:         vol.Labels,
		TopologyLabels: model.TopologyLabels(vol.TopologyLabels),
		Filesystem:     model.FsTypeFromString(string(vol.FsType)),

		CreatedAt: vol.CreatedAt,
		UpdatedAt: vol.UpdatedAt,
		Version:   vol.Version,
	}

	m := vol.Master
	v.Master = &model.Deployment{
		ID:         m.Id,
		Node:       string(m.NodeID),
		Health:     health.MasterFromString(string(m.Health)),
		Promotable: m.Promotable,
	}

	replicas := []*model.Deployment{}

	if vol.Replicas != nil {
		replicas = make([]*model.Deployment, len(*vol.Replicas))
		for i, r := range *vol.Replicas {
			replicas[i] = &model.Deployment{
				ID:         r.Id,
				Node:       string(r.NodeID),
				Health:     health.ReplicaFromString(string(r.Health)),
				Promotable: r.Promotable,
			}

			p := r.SyncProgress

			if (p != openapi.SyncProgress{}) {
				replicas[i].SyncProgress = &model.SyncProgress{
					BytesRemaining:            p.BytesRemaining,
					ThroughputBytes:           p.ThroughputBytes,
					EstimatedSecondsRemaining: p.EstimatedSecondsRemaining,
				}
			}
		}
	}

	v.Replicas = replicas

	return v, nil
}

func DecodeNamespace(ns openapi.Namespace) (*model.Namespace, error) {
	return &model.Namespace{
		ID:     string(ns.Id),
		Name:   ns.Name,
		Labels: ns.Labels,

		CreatedAt: ns.CreatedAt,
		UpdatedAt: ns.UpdatedAt,
		Version:   ns.Version,
	}, nil
}

func DecodePolicyGroup(policyGroup openapi.PolicyGroup) (*model.PolicyGroup, error) {
	users := []*model.PolicyGroupMember{}
	if policyGroup.Users != nil {
		users = make([]*model.PolicyGroupMember, 0, len(policyGroup.Users))
		for _, u := range policyGroup.Users {
			users = append(users, &model.PolicyGroupMember{
				ID:       string(u.Id),
				Username: u.Username,
			})
		}
	}

	specs := []*model.PolicyGroupSpec{}
	if policyGroup.Specs != nil {
		specs = make([]*model.PolicyGroupSpec, 0, len(*policyGroup.Specs))
		for _, spec := range *policyGroup.Specs {
			specs = append(specs, &model.PolicyGroupSpec{
				NamespaceID:  string(spec.NamespaceID),
				ResourceType: spec.ResourceType,
				ReadOnly:     spec.ReadOnly,
			})
		}
	}

	return &model.PolicyGroup{
		ID:        string(policyGroup.Id),
		Name:      policyGroup.Name,
		Users:     users,
		Specs:     specs,
		CreatedAt: policyGroup.CreatedAt,
		UpdatedAt: policyGroup.UpdatedAt,
		Version:   policyGroup.Version,
	}, nil
}

func DecodeUser(user openapi.User) (*model.User, error) {

	groups := []string{}

	if user.Groups != nil {
		groups = make([]string, len(*user.Groups))
		for i, groupID := range *user.Groups {
			groups[i] = string(groupID)
		}
	}

	return &model.User{
		ID:       string(user.Id),
		Username: user.Username,

		IsAdmin: user.IsAdmin,
		Groups:  groups,

		CreatedAt: user.CreatedAt,
		UpdatedAt: user.UpdatedAt,
		Version:   user.Version,
	}, nil
}

func DecodeNFSConfig(nfsConfig openapi.NfsConfig) model.NFSConfig {
	cfg := model.NFSConfig{
		Exports:         make([]model.NFSExportConfig, 0),
		ServiceEndpoint: "",
	}

	if nfsConfig.ServiceEndpoint != nil {
		cfg.ServiceEndpoint = *nfsConfig.ServiceEndpoint
	}

	if nfsConfig.Exports != nil {
		for _, e := range *nfsConfig.Exports {
			cfg.Exports = append(cfg.Exports, DecodeNFSExportConfig(e))
		}
	}

	return cfg
}

func DecodeNFSExportConfig(nfsExportConfig openapi.NfsExportConfig) model.NFSExportConfig {
	cfg := model.NFSExportConfig{
		ExportID:   uint(nfsExportConfig.ExportID),
		Path:       nfsExportConfig.Path,
		PseudoPath: nfsExportConfig.PseudoPath,
		ACLs:       make([]model.NFSExportConfigACL, 0, len(nfsExportConfig.Acls)),
	}

	for _, a := range nfsExportConfig.Acls {
		cfg.ACLs = append(cfg.ACLs, model.NFSExportConfigACL{
			Identity: model.NFSExportConfigACLIdentity{
				IdentityType: a.Identity.IdentityType,
				Matcher:      a.Identity.Matcher,
			},
			SquashConfig: model.NFSExportConfigACLSquashConfig{
				GID:    a.SquashConfig.Gid,
				UID:    a.SquashConfig.Uid,
				Squash: a.SquashConfig.Squash,
			},
			AccessLevel: a.AccessLevel,
		})
	}
	return cfg
}

func EncodeNFSExport(export model.NFSExportConfig) openapi.NfsExportConfig {
	cfg := openapi.NfsExportConfig{
		ExportID:   uint64(export.ExportID),
		Path:       export.Path,
		PseudoPath: export.PseudoPath,
		Acls:       []openapi.NfsAcl{},
	}

	for _, a := range export.ACLs {
		cfg.Acls = append(cfg.Acls, openapi.NfsAcl{
			Identity: openapi.NfsAclIdentity{
				IdentityType: a.Identity.IdentityType,
				Matcher:      a.Identity.Matcher,
			},
			SquashConfig: openapi.NfsAclSquashConfig{
				Uid:    a.SquashConfig.UID,
				Gid:    a.SquashConfig.GID,
				Squash: a.SquashConfig.Squash,
			},
			AccessLevel: a.AccessLevel,
		})
	}

	return cfg
}

func EncodeFsType(filesystem model.FsType) (openapi.FsType, error) {
	v := openapi.FsType(filesystem.String())
	switch v {
	case openapi.FSTYPE_EXT2, openapi.FSTYPE_EXT3,
		openapi.FSTYPE_EXT4, openapi.FSTYPE_XFS,
		openapi.FSTYPE_BTRFS, openapi.FSTYPE_BLOCK:
		return v, nil
	default:
		return "", apiclient.NewEncodingError(
			errors.New("unknown fs type"),
			v,
			filesystem,
		)
	}
}

func EncodeLogLevel(level model.LogLevel) (openapi.LogLevel, error) {
	v := openapi.LogLevel(level.String())
	switch v {
	case openapi.LOGLEVEL_DEBUG, openapi.LOGLEVEL_INFO,
		openapi.LOGLEVEL_WARN, openapi.LOGLEVEL_ERROR:
		return v, nil
	default:
		return "", apiclient.NewEncodingError(
			errors.New("unknown log level"),
			v,
			level,
		)
	}
}

func EncodeLogFormat(format model.LogFormat) (openapi.LogFormat, error) {
	v := openapi.LogFormat(format.String())
	switch v {
	case openapi.LOGFORMAT_DEFAULT, openapi.LOGFORMAT_JSON:
		return v, nil
	default:
		return "", apiclient.NewEncodingError(
			errors.New("unknown log format"),
			v,
			format,
		)
	}
}
